// 安魂（莉莉专属限定佩枪，5★）
//
// 90 级面板：攻击 412.5、共鸣效率 77.04%（副属性已计入面板）。
//
// 谐振「落梦归魂」(R1/R2/R3/R4/R5)：
//   生命值提升 12%/15%/18%/21%/24%；
//   施放共鸣解放时，回复 8/10/12/14/16 点协奏能量，每 20 秒可触发 1 次；
//   重击造成治疗时，队伍中的角色获得【落梦归魂】，持续 30 秒；
//     该角色获得同奏或响应同奏时，攻击提升 16%/20%/24%/28%/32%，持续 30 秒；
//   重击造成治疗时，队伍中的登场角色获得 24%/30%/36%/42%/48% 声骸技能伤害加成，
//     持续 30 秒。同名效果之间不可叠加。
//
// 实现口径：
//   - 生命提升、共鸣效率属于静态面板属性，面板已包含，不重复计入。
//   - 【落梦归魂】的攻击提升依赖「获得/响应同奏」，默认按已触发计入自身输出，
//     可用 options.weaponEffectActive === false 关闭。
//   - 声骸技能伤害加成只作用于声骸技能，不并入莉莉本体技能伤害。

const wiki = {
  id: '21030076',
  name: '安魂',
  star: '5',
  weaponType: '佩枪',
  currentVersion: '3.8',
  effectText: '落梦归魂\n\n谐振(1/2/3/4/5)阶\n\n生命值提升12%/15%/18%/21%/24%。施放共鸣解放时，回复8/10/12/14/16点协奏能量，每20秒可触发1次。重击造成治疗时，队伍中的角色获得【落梦归魂】状态，持续30秒。【落梦归魂】持续期间，若该角色获得同奏或响应同奏，该角色攻击提升16%/20%/24%/28%/32%，持续30秒，【落梦归魂】持续时间结束时移除该效果。重击造成治疗时，队伍中的登场角色获得24%/30%/36%/42%/48%声骸技能伤害加成，持续30秒。同名效果之间不可叠加。'
};

const UNISON_ATTACK = [0.16, 0.20, 0.24, 0.28, 0.32];
const ECHO_SKILL_DAMAGE = [0.24, 0.30, 0.36, 0.42, 0.48];

export default {
  name: '安魂',
  wiki,

  apply({ panel, options }) {
    const reson = Math.max(1, Math.min(5, Number(panel?.weaponResonLevel || 1)));

    const buff = {
      attackPercent: 0,
      damageBonus: 0,
      source: '安魂'
    };

    // 未获得同奏 / 未处于【落梦归魂】：不结算触发态攻击提升。
    if (options?.weaponEffectActive === false) {
      return buff;
    }

    // 【落梦归魂】：获得/响应同奏时攻击提升。
    buff.attackPercent += UNISON_ATTACK[reson - 1];

    // 队伍向的声骸技能伤害加成另存，供队伍口径使用，不并入莉莉本体伤害。
    buff.supportEchoSkillDamageBonus = ECHO_SKILL_DAMAGE[reson - 1];

    return buff;
  }
};
